export function generateWriting(userMessage, mode) {
  if (mode === 'single') {
    return {
      title: '文案撰寫提示詞',
      body: `請扮演一位專業的文案撰寫專家。

你的任務是撰寫一篇文案，需求如下：
${userMessage}

限制與要求：
- 目標受眾：一般大眾（請根據需求調整）
- 語氣：專業但具親和力
- 格式：請包含吸睛標題、引人入勝的開頭、條理分明的內文、有力的結語。
- 請使用繁體中文撰寫。
`
    };
  } else if (mode === 'chain') {
    return {
      steps: [
        {
          name: '釐清受眾與調性',
          prompt: `我需要撰寫一篇文案，需求如下：
${userMessage}

在開始寫作之前，請列出你需要向我釐清的幾個關鍵問題，例如：
1. 目標受眾是誰？
2. 希望傳達的核心訊息是什麼？
3. 語氣應該是正式、幽默還是感性？`
        },
        {
          name: '產出大綱與草稿',
          prompt: `請根據我們先前釐清的內容，為這篇文案產出大綱，以及初步的草稿。

原始需求：
${userMessage}

草稿請包含：
- 建議標題
- 開頭段落
- 核心內文重點`
        },
        {
          name: '潤飾與定稿',
          prompt: `請幫我潤飾目前的文案草稿。請檢查：
1. 語句是否通順流暢？
2. 遣詞用字是否精準？
3. 結構是否吸引人繼續閱讀？

請直接提供最終修訂定稿。`
        }
      ]
    };
  }
}
